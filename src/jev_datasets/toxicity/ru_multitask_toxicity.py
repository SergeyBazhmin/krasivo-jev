class RuMultitaskToxicityDataset(JevDataset):
    type = DatasetType.NOUL

    def prepare(self):
        def samples(row: dict) -> list[dict]:
            state = with_context(ABOUT, row["text"], "Сообщение")
            return [
                make_sample(state, pick_question(versions, row["text"]), OPTIONS, "yes" if row[category] else "no")
                for category, versions in QUESTIONS.items()
            ]

        self.data = self.data.filter(lambda x: bool(x["text"].strip()))
        self.data = self.data.map(
            explode(samples), batched=True, remove_columns=self.source_columns, features=SAMPLE_FEATURES
        )


ru_multitask_toxicity_dataset = RuMultitaskToxicityDataset(
    name="ru_multitask_toxicity", hf_path="AtesiT/ru-multitask-toxicity"
)
